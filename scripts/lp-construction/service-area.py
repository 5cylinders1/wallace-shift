"""Build LP Construction's service-area ZIP list: a 45-minute drive from
downtown Kansas City, MO (the owner's answer to intake question 4).

    python3 -I scripts/lp-construction/service-area.py

1. Downloads the Census 2024 ZCTA gazetteer (ZIP-area centroids, about 1 MB)
   into output/lp-construction/census/ unless it is already there.
2. Keeps ZCTAs within 70 straight-line miles of the center.
3. Asks the public OSRM demo router for the free-flow drive time from the
   center to each centroid, 80 at a time, one request every 1.5 seconds.
4. Writes src/demos/lp-construction/serviceAreaZips.ts:
     in    drive time up to 45 minutes
     edge  over 45 and up to 55 minutes ("call or text to confirm")
   Everything else is outside the area.

Free-flow times ignore traffic, and a ZIP's centroid stands in for every
address in it; the edge band covers both. The owner approves the list.
"""
import io, json, math, os, time, urllib.request, zipfile
from datetime import date

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
WORK = os.path.join(ROOT, 'output', 'lp-construction', 'census')
OUT = os.path.join(ROOT, 'src', 'demos', 'lp-construction', 'serviceAreaZips.ts')
GAZETTEER = 'https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_zcta_national.zip'
OSRM = 'https://router.project-osrm.org/table/v1/driving/'
CENTER = (39.1001, -94.5781)  # Kansas City, MO City Hall, downtown
LIMIT_MIN, EDGE_MIN, RADIUS_MI, BATCH = 45, 55, 70, 80
AGENT = {'User-Agent': 'zip-drive-time-script/1.0'}


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers=AGENT), timeout=60) as response:
        return response.read()


def miles(a, b) -> float:
    lat1, lon1, lat2, lon2 = map(math.radians, (*a, *b))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 3958.8 * 2 * math.asin(math.sqrt(h))


def zctas():
    os.makedirs(WORK, exist_ok=True)
    path = os.path.join(WORK, os.path.basename(GAZETTEER))
    if not os.path.exists(path):
        with open(path, 'wb') as handle:
            handle.write(fetch(GAZETTEER))
    with zipfile.ZipFile(path) as archive:
        name = next(item for item in archive.namelist() if item.endswith('.txt'))
        lines = io.TextIOWrapper(archive.open(name), encoding='utf-8').read().splitlines()
    header = [column.strip() for column in lines[0].split('\t')]
    geoid, lat, lon = header.index('GEOID'), header.index('INTPTLAT'), header.index('INTPTLONG')
    for row in lines[1:]:
        cells = [cell.strip() for cell in row.split('\t')]
        point = (float(cells[lat]), float(cells[lon]))
        if miles(CENTER, point) <= RADIUS_MI:
            yield cells[geoid], point


def drive_minutes(points):
    minutes = []
    for start in range(0, len(points), BATCH):
        chunk = points[start:start + BATCH]
        coords = ';'.join(f'{lon:.5f},{lat:.5f}' for lat, lon in [CENTER, *chunk])
        body = json.loads(fetch(f'{OSRM}{coords}?sources=0&annotations=duration'))
        if body.get('code') != 'Ok':
            raise SystemExit(f'OSRM error: {body.get("code")} {body.get("message")}')
        minutes += [None if seconds is None else seconds / 60 for seconds in body['durations'][0][1:]]
        time.sleep(1.5)
    return minutes


def main():
    candidates = sorted(zctas())
    times = drive_minutes([point for _, point in candidates])
    inside = [zip_ for (zip_, _), t in zip(candidates, times) if t is not None and t <= LIMIT_MIN]
    edge = [zip_ for (zip_, _), t in zip(candidates, times) if t is not None and LIMIT_MIN < t <= EDGE_MIN]
    with open(os.path.join(WORK, 'drive-times.json'), 'w') as handle:
        json.dump({zip_: None if t is None else round(t, 1) for (zip_, _), t in zip(candidates, times)}, handle, indent=1)
    wrap = lambda items: '\n'.join('  ' + ', '.join(f"'{z}'" for z in items[i:i + 10]) + ',' for i in range(0, len(items), 10))
    with open(OUT, 'w') as handle:
        handle.write(
            '/**\n'
            ' * Generated by scripts/lp-construction/service-area.py; do not edit by hand.\n'
            f' * Free-flow drive time from downtown Kansas City, MO ({CENTER[0]}, {CENTER[1]}) to each\n'
            ' * Census 2024 ZCTA centroid, from the public OSRM router. The owner approves the list.\n'
            ' */\n'
            f"export const AREA_COMPUTED = '{date.today().isoformat()}'\n"
            f'export const AREA_LIMIT_MINUTES = {LIMIT_MIN}\n'
            f'export const AREA_EDGE_MINUTES = {EDGE_MIN}\n\n'
            f'/** {len(inside)} ZIPs within {LIMIT_MIN} minutes. */\n'
            f'export const INSIDE_ZIPS: readonly string[] = [\n{wrap(inside)}\n]\n\n'
            f'/** {len(edge)} ZIPs between {LIMIT_MIN} and {EDGE_MIN} minutes. */\n'
            f'export const EDGE_ZIPS: readonly string[] = [\n{wrap(edge)}\n]\n'
        )
    print(f'{len(candidates)} candidates, {len(inside)} inside, {len(edge)} edge, {sum(t is None for t in times)} unroutable')


if __name__ == '__main__':
    main()
